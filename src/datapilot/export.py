_PROJECT_README = """# DataPilot project

Generated by DataPilot.

- Task: {task} on target `{target}`
- Selected: pipeline `{pipeline}` + model `{model}`{smote_note}

## Run
    pip install -r requirements.txt
    python train.py your_data.csv      # retrains and prints held-out metrics
    python predict.py new_data.csv     # predicts with model.joblib

`datapilot/` is the exact library code used for this run, so results reproduce.
`train.py` is the whole program in one file (imports, settings, load, split,
features, model, train, tune, evaluate, save). Edit it and run it again.
"""

_BASE_REQUIREMENTS = ["pandas", "numpy", "scipy", "scikit-learn", "imbalanced-learn", "joblib", "openpyxl"]


def _project_requirements(model_name: str) -> str:
    """Only the boosting libraries the chosen model actually needs, so the exported
    project installs fast and still loads its model.joblib."""
    extra = [lib for key, lib in (("xgboost", "xgboost"), ("lightgbm", "lightgbm"), ("catboost", "catboost"))
             if key in model_name.lower()]
    return "\n".join(_BASE_REQUIREMENTS + extra) + "\n"


def build_project_zip(
    *,
    target: str,
    task_type_value: str,
    priority_value: str,
    preserve_missingness: bool,
    options,                      # PipelineOptions
    pipeline_name: str,
    model_name: str,              # base model name, without the " + SMOTE" suffix
    best_params: dict,
    uses_smote: bool,
    feature_columns: list[str],
    fitted_pipeline,
    log_target: bool = False,
    label_encoder=None,
    test_csv: bytes | None = None,   # the user's own test file, bundled so train.py reproduces the same final test
) -> bytes:
    """A runnable project: train.py + predict.py + the library source + the
    already-fitted model. train.py rebuilds the identical pipeline through
    the same planner with the same options, so it is not a re-implementation
    that could drift from what was evaluated."""
    import dataclasses
    import zipfile
    from pathlib import Path

    pkg_dir = Path(__file__).parent
    skip = {"app.py", "theme.py"}
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
        for f in sorted(pkg_dir.glob("*.py")):
            if f.name not in skip:
                z.write(f, f"datapilot_project/datapilot/{f.name}")
        try:
            from .notebook_export import generate_train_script
            train_src = generate_train_script(
                fitted_pipeline=fitted_pipeline, target=target, task=task_type_value,
                pipeline_name=pipeline_name, model_name=model_name, best_params=best_params,
                uses_smote=uses_smote, excluded=list(options.excluded_columns), log_target=log_target,
                test_file="test_file.csv" if test_csv else None)
            compile(train_src, "train.py", "exec")
        except Exception:  # fall back to the configuration-style script
            train_src = _TRAIN_TEMPLATE.format(
                target=target, task=task_type_value, priority=priority_value,
                preserve=preserve_missingness, excluded=list(options.excluded_columns),
                options=dataclasses.asdict(options), pipeline=pipeline_name, model=model_name,
                params=dict(best_params or {}), smote=uses_smote,
            )
        z.writestr("datapilot_project/train.py", train_src)
        if test_csv:
            z.writestr("datapilot_project/test_file.csv", test_csv)
        try:
            from .notebook_export import generate_submission_script
            sub_src = generate_submission_script(
                fitted_pipeline=fitted_pipeline, target=target, task=task_type_value, model_name=model_name,
                best_params=best_params, uses_smote=uses_smote, excluded=list(options.excluded_columns),
                feature_columns=list(feature_columns), log_target=log_target)
            compile(sub_src, "make_submission.py", "exec")
            z.writestr("datapilot_project/make_submission.py", sub_src)
        except Exception:  # noqa: BLE001  (optional file; the app still builds submissions itself)
            pass
        z.writestr("datapilot_project/predict.py", _PREDICT_TEMPLATE.format(
            target=target, features=list(feature_columns)))
        z.writestr("datapilot_project/requirements.txt", _project_requirements(model_name))
        z.writestr("datapilot_project/README.md", _PROJECT_README.format(
            task=task_type_value, target=target, pipeline=pipeline_name, model=model_name,
            smote_note=" with SMOTE" if uses_smote else ""))
        z.writestr("datapilot_project/model.joblib", serialize_pipeline(fitted_pipeline))
        le = io.BytesIO(); joblib.dump(label_encoder, le)
        z.writestr("datapilot_project/label_encoder.joblib", le.getvalue())
    return buf.getvalue()
